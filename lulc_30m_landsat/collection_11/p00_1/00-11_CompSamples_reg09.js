      'red_median',	'gcvi_median_wet',	'ndvi_median',	'cai_median_wet',	'evi2_median_wet',	'gcvi_max',	'gcvi_median',	
      'savi_median',	'cai_median',	'gcvi_amp',	'green_median_wet',	'ndvi_max',	'red_min',	'green_median_dry',	
      'cai_min',	'cai_max',	'savi_median_wet',	'swir2_median',	'gcvi_median_dry',	'evi2_median_dry',	'savi_amp',	
      'gcvi_min',	'green_median',	'savi_max',	'ndwi_stdDev',	'swir1_max',	'shade_median_dry',	'savi_median_dry',	
      'ndvi_median_dry',	'ndwi_min',	'red_stdDev',	'swir2_median_wet',	'evi2_median',	'savi_min',	'red_median_dry',	
      'gcvi_stdDev',	'blue_min',	'red_median_wet',	'swir1_median_dry',	'evi2_amp',	'shade_min',	'evi2_max',	'red_max',	
      'nir_median',	'ndwi_median',	'cai_amp',	'hallcover_median',	'ndwi_median_wet',	'hallcover_median_dry',	
      'ndwi_median_dry',	'gv_median',	'swir2_median_dry',	'blue_max',	'shade_median_wet',	'ndvi_stdDev',	'green_min',	
